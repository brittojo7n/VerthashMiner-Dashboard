#!/usr/bin/env node
"use strict";

/**
 * Builds a self-contained test environment under `.testenv/`:
 *
 *   .testenv/
 *     .env                 the supplied deployment configuration, re-pointed
 *                          at the mock miner and an ephemeral-safe port
 *     miner/
 *       VerthashMiner      executable stand-in (the mock miner)
 *       verthash.dat       synthetic data file (see the warning below)
 *
 * ---------------------------------------------------------------------------
 * About verthash.dat
 * ---------------------------------------------------------------------------
 * A REAL verthash.dat is ~1.2 GB and is derived from the Vertcoin blockchain.
 * It cannot be synthesised here, and nothing in this repository can generate a
 * valid one. The only supported way to produce it is the miner itself:
 *
 *     VerthashMiner --gen-verthash-data verthash.dat
 *
 * (upstream: src/main.cpp, `--gen-verthash-data`, "This may take a while...")
 *
 * The file produced by this script is a small deterministic placeholder whose
 * ONLY purpose is to exercise the dashboard's file-path handling. It will be
 * rejected by the real miner ("Invalid Verthash data file size"), which is
 * itself a useful failure mode to test.
 * ---------------------------------------------------------------------------
 *
 * Usage:  node tools/setup-test-env.js [--size-mb 1] [--dir .testenv]
 */

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const ROOT = path.resolve(__dirname, "..");

function parseArgs(argv) {
  const args = { dir: ".testenv", sizeMb: 1, port: 4067 };
  for (let i = 0; i < argv.length; i++) {
    const key = argv[i];
    const value = argv[i + 1];
    if (key === "--dir" && value) args.dir = value;
    if (key === "--size-mb" && value) args.sizeMb = Math.max(0, Number(value) || 0);
    if (key === "--port" && value) args.port = Number(value) || 4067;
  }
  return args;
}

/** Deterministic pseudo-random payload, written in 1 MiB chunks. */
function writePlaceholderData(target, sizeMb) {
  const chunk = Buffer.alloc(1024 * 1024);
  const seed = crypto.createHash("sha256").update("verthash-placeholder").digest();
  for (let i = 0; i < chunk.length; i++) chunk[i] = seed[i % seed.length] ^ (i & 0xff);

  const fd = fs.openSync(target, "w");
  try {
    for (let i = 0; i < sizeMb; i++) fs.writeSync(fd, chunk);
  } finally {
    fs.closeSync(fd);
  }
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const base = path.resolve(ROOT, args.dir);
  const minerDir = path.join(base, "miner");
  fs.mkdirSync(minerDir, { recursive: true });

  // 1. Miner stand-in -------------------------------------------------------
  const minerName = process.platform === "win32" ? "VerthashMiner.cmd" : "VerthashMiner";
  const minerPath = path.join(minerDir, minerName);
  const mock = path.join(ROOT, "test", "mocks", "mock-miner.js");

  if (process.platform === "win32") {
    fs.writeFileSync(minerPath, `@echo off\r\nnode "${mock}" %*\r\n`);
  } else {
    fs.writeFileSync(minerPath, `#!/bin/sh\nexec "${process.execPath}" "${mock}" "$@"\n`);
    fs.chmodSync(minerPath, 0o755);
  }

  // 2. verthash.dat placeholder --------------------------------------------
  const dataPath = path.join(minerDir, "verthash.dat");
  writePlaceholderData(dataPath, args.sizeMb);

  // 3. .env ------------------------------------------------------------------
  const envPath = path.join(base, ".env");
  const env = [
    "# Generated by tools/setup-test-env.js - test environment only.",
    "# Mirrors the supplied deployment configuration, with the miner replaced",
    "# by a mock that streams the canonical VerthashMiner console output.",
    `PORT=${args.port}`,
    "HOST=0.0.0.0",
    "FORWARD_CONSOLE=true",
    "PASSPHRASE=7654321abcdefg",
    `SESSION_SECRET=${crypto.randomBytes(32).toString("hex")}`,
    `MINER_EXE=${minerName}`,
    `MINER_CWD=${minerDir}`,
    "MINER_ARGS=-u vtc1qwddxt3rmwx00ev9yg4qcwpxnguw5zm7mwej2xk -p c=VTC " +
      "-o stratum+tcp://verthash.sea.mine.zpool.ca:6144 " +
      `--verthash-data ${dataPath} --all-cu-devices`,
    ""
  ].join("\n");
  fs.writeFileSync(envPath, env);

  const size = fs.statSync(dataPath).size;
  process.stdout.write(
    [
      `Test environment ready in ${base}`,
      `  .env            ${envPath}`,
      `  miner           ${minerPath}`,
      `  verthash.dat    ${dataPath} (${(size / 1048576).toFixed(1)} MB placeholder)`,
      "",
      "WARNING: verthash.dat is a PLACEHOLDER, not a valid Verthash data file.",
      "         Generate the real ~1.2 GB file with:",
      "             VerthashMiner --gen-verthash-data verthash.dat",
      "",
      "Run the dashboard against it with:",
      `  ENV_FILE=${envPath} node ${path.join(ROOT, "server.js")}`,
      `  (Windows: set ENV_FILE=${envPath} && node server.js)`,
      ""
    ].join("\n")
  );
}

if (require.main === module) main();

module.exports = { writePlaceholderData };
